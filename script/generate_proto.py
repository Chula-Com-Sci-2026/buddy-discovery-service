"""Generate Ruby messages/service definitions from a compiled protobuf descriptor.

Run with Python grpcio-tools installed: python script/generate_proto.py
"""
from pathlib import Path
import base64
import tempfile
from grpc_tools import protoc
from google.protobuf.descriptor_pb2 import FileDescriptorSet

root = Path(__file__).resolve().parents[1]
source = "buddy_discovery/v1/buddy_discovery.proto"
with tempfile.TemporaryDirectory() as work:
    descriptor = Path(work) / "descriptor.pb"
    assert protoc.main(["protoc", f"-I{root / 'proto'}", f"--descriptor_set_out={descriptor}", source]) == 0
    schema = FileDescriptorSet.FromString(descriptor.read_bytes()).file[0]
payload = base64.b64encode(schema.SerializeToString()).decode()
messages = "# Generated by script/generate_proto.py; do not edit.\nrequire 'google/protobuf'\nrequire 'base64'\n"
messages += f"Google::Protobuf::DescriptorPool.generated_pool.add_serialized_file(Base64.decode64('{payload}'))\n"
messages += "module BuddyDiscovery\n  module V1\n"
for message in schema.message_type:
    messages += f'    {message.name} = Google::Protobuf::DescriptorPool.generated_pool.lookup("{schema.package}.{message.name}").msgclass\n'
messages += "  end\nend\n"
service = schema.service[0]
stubs = "# Generated by script/generate_proto.py; do not edit.\nrequire 'grpc'\nrequire 'buddy_discovery/v1/buddy_discovery_pb'\n"
stubs += f"module BuddyDiscovery\n  module V1\n    module {service.name}\n      class Service\n        include GRPC::GenericService\n        self.marshal_class_method = :encode\n        self.unmarshal_class_method = :decode\n        self.service_name = '{schema.package}.{service.name}'\n"
for method in service.method:
    stubs += f"        rpc :{method.name}, ::BuddyDiscovery::V1::{method.input_type.split('.')[-1]}, ::BuddyDiscovery::V1::{method.output_type.split('.')[-1]}\n"
stubs += "      end\n      Stub = Service.rpc_stub_class\n    end\n  end\nend\n"
(root / 'lib/buddy_discovery/v1/buddy_discovery_pb.rb').write_text(messages)
(root / 'lib/buddy_discovery/v1/buddy_discovery_services_pb.rb').write_text(stubs)
